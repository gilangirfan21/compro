<?php

use App\Enums\PostStatus;
use App\Filament\Pages\ManageSettings;
use App\Filament\Resources\Messages\MessageResource;
use App\Filament\Resources\Messages\Pages\ListMessages;
use App\Filament\Resources\Messages\Pages\ViewMessage;
use App\Filament\Resources\Portfolios\Pages\CreatePortfolio;
use App\Filament\Resources\Portfolios\Pages\ListPortfolios;
use App\Filament\Resources\Posts\Pages\CreatePost;
use App\Filament\Resources\Posts\Pages\ListPosts;
use App\Filament\Resources\Services\Pages\CreateService;
use App\Filament\Resources\Services\Pages\EditService;
use App\Filament\Resources\Services\Pages\ListServices;
use App\Models\Message;
use App\Models\Portfolio;
use App\Models\Post;
use App\Models\Service;
use App\Models\Setting;
use App\Models\User;
use Filament\Facades\Filament;
use Illuminate\Foundation\Testing\RefreshDatabase;
use Illuminate\Http\UploadedFile;
use Illuminate\Support\Facades\Storage;
use Livewire\Livewire;
use Spatie\Permission\Models\Permission;

uses(RefreshDatabase::class);

beforeEach(function () {
    Filament::setCurrentPanel('admin');

    $permissions = ['View:ManageSettings'];

    foreach (['Service', 'Portfolio', 'Post', 'Message'] as $model) {
        foreach (['ViewAny', 'View', 'Create', 'Update', 'Delete', 'DeleteAny', 'Reorder'] as $ability) {
            $permissions[] = "{$ability}:{$model}";
        }
    }

    $user = User::factory()->create();
    $user->givePermissionTo(array_map(
        fn (string $name): Permission => Permission::create(['name' => $name, 'guard_name' => 'web']),
        $permissions,
    ));

    $this->actingAs($user);
});

it('renders the content list pages', function (string $page) {
    Livewire::test($page)->assertOk();
})->with([
    ListServices::class,
    ListPortfolios::class,
    ListPosts::class,
    ListMessages::class,
]);

it('generates a slug from the title on create', function () {
    Livewire::test(CreateService::class)
        ->fillForm(['title' => 'Konsultasi IT', 'sort_order' => 1])
        ->call('create')
        ->assertHasNoFormErrors();

    expect(Service::first()->slug)->toBe('konsultasi-it');
});

it('keeps slugs unique when generated by the model', function () {
    Portfolio::create(['title' => 'Website Toko']);
    $second = Portfolio::create(['title' => 'Website Toko']);

    expect($second->slug)->toBe('website-toko-2');
});

it('does not change the slug when the title is edited', function () {
    $service = Service::create(['title' => 'Lama']);

    Livewire::test(EditService::class, ['record' => $service->getKey()])
        ->fillForm(['title' => 'Baru'])
        ->call('save')
        ->assertHasNoFormErrors();

    expect($service->refresh())
        ->title->toBe('Baru')
        ->slug->toBe('lama');
});

it('rejects a duplicate slug', function () {
    Portfolio::create(['title' => 'Proyek A']);

    Livewire::test(CreatePortfolio::class)
        ->fillForm(['title' => 'Proyek B', 'slug' => 'proyek-a'])
        ->call('create')
        ->assertHasFormErrors(['slug' => 'unique']);
});

it('stores uploaded images on the public disk', function () {
    Storage::fake('public');

    Livewire::test(CreateService::class)
        ->fillForm([
            'title' => 'Desain',
            'sort_order' => 0,
            'image' => UploadedFile::fake()->image('icon.png'),
        ])
        ->call('create')
        ->assertHasNoFormErrors();

    $image = Service::first()->image;

    expect($image)->toStartWith('services/');
    Storage::disk('public')->assertExists($image);
});

it('fills published_at when a post is published', function () {
    Livewire::test(CreatePost::class)
        ->fillForm([
            'title' => 'Berita Pertama',
            'content' => '<p>Isi berita</p>',
            'status' => PostStatus::Published->value,
        ])
        ->call('create')
        ->assertHasNoFormErrors();

    $post = Post::first();

    expect($post->status)->toBe(PostStatus::Published)
        ->and($post->published_at)->not->toBeNull()
        ->and(Post::published()->count())->toBe(1);
});

it('keeps draft posts out of the published scope', function () {
    Post::create(['title' => 'Draft', 'content' => 'x', 'status' => PostStatus::Draft]);
    Post::create(['title' => 'Nanti', 'content' => 'x', 'status' => PostStatus::Published, 'published_at' => now()->addDay()]);

    expect(Post::published()->count())->toBe(0);
});

it('saves settings into a single record', function () {
    Livewire::test(ManageSettings::class)
        ->assertOk()
        ->fillForm([
            'company_name' => 'PT Contoh',
            'email' => 'info@contoh.test',
            'social_links' => [
                ['platform' => 'instagram', 'url' => 'https://instagram.com/contoh'],
            ],
        ])
        ->call('save')
        ->assertHasNoFormErrors();

    Livewire::test(ManageSettings::class)
        ->assertSchemaStateSet(['company_name' => 'PT Contoh'])
        ->fillForm(['company_name' => 'PT Contoh Baru'])
        ->call('save')
        ->assertHasNoFormErrors();

    expect(Setting::count())->toBe(1)
        ->and(Setting::current()->company_name)->toBe('PT Contoh Baru')
        ->and(Setting::current()->social_links)->toBe([
            ['platform' => 'instagram', 'url' => 'https://instagram.com/contoh'],
        ]);
});

it('requires the company name in settings', function () {
    Livewire::test(ManageSettings::class)
        ->fillForm(['company_name' => ''])
        ->call('save')
        ->assertHasFormErrors(['company_name' => 'required']);
});

it('keeps messages read-only and marks them read when opened', function () {
    $message = Message::create([
        'name' => 'Budi',
        'email' => 'budi@example.com',
        'subject' => 'Tanya harga',
        'message' => 'Halo',
    ]);

    expect(MessageResource::canCreate())->toBeFalse()
        ->and(MessageResource::hasPage('create'))->toBeFalse()
        ->and(MessageResource::hasPage('edit'))->toBeFalse()
        ->and(MessageResource::getNavigationBadge())->toBe('1');

    Livewire::test(ViewMessage::class, ['record' => $message->getKey()])
        ->assertOk()
        ->assertSee('Tanya harga');

    expect($message->refresh()->is_read)->toBeTrue()
        ->and(MessageResource::getNavigationBadge())->toBeNull();
});
